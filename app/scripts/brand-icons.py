rows = []
for bid, slug, old, name, hosts in BRANDS:
    svg = open(os.path.join(old_dir if old else new_dir, slug + '.svg'), encoding='utf-8').read()
    d = re.search(r' d="([^"]+)"', svg).group(1)
    rows.append(f"  {{ id: {json.dumps(bid)}, name: {json.dumps(name)}, hosts: {json.dumps(hosts)}, path: {json.dumps(d)} }},")

