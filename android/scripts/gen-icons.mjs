#!/usr/bin/env node
// Generates android/designsystem/.../LinkordIcons.kt from the web client's icons (app/src/components/Icons.tsx):
// the same names (I.Hash -> LinkordIcons.Hash), the same Heroicons outline/solid files and the same shapes drawn
// there for what Heroicons lacks. Run after changing Icons.tsx: node android/scripts/gen-icons.mjs
// Needs app/node_modules (cd app && bun install) for the Heroicons files.
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = fileURLToPath(new URL('../..', import.meta.url));
const src = readFileSync(join(root, 'app/src/components/Icons.tsx'), 'utf8');
const out = join(root, 'android/designsystem/src/main/kotlin/com/linkord/designsystem/LinkordIcons.kt');

// 1. The Heroicons files, by the name Icons.tsx imports them as.
const svgs = {};
for (const [, name, file] of src.matchAll(/^import (\w+) from 'heroicons\/([^']+)\?raw';$/gm)) {
  svgs[name] = readFileSync(join(root, 'app/node_modules/heroicons', file), 'utf8');
}

// 2. Icons.tsx's definitions, run with helpers that return the shapes instead of a Solid component.
const start = src.indexOf('const hero = ');
const end = src.indexOf('/** The app icon');
let defs = src.slice(start, end);
// The tilted pin is a component wrapping PinIcon: recorded as a rotation instead.
defs = defs.replace(/^export const Pin = \(p: P\) => <PinIcon[^\n]*\n/m, 'out.Pin = { ...PinIcon, rotate: 40 };\n');
defs = defs.replace(/^export const (\w+) = /gm, 'out.$1 = ');
const later = src.slice(src.indexOf('// REC (studio + player).')).replace(/^export const (\w+) = /gm, 'out.$1 = ');
const tail = src.slice(src.indexOf('export const Send = '), src.indexOf('/**\n * A link')).replace(/^export const (\w+) = /gm, 'out.$1 = ');
const module = `
${Object.entries(svgs).map(([k, v]) => `const ${k} = ${JSON.stringify(v)};`).join('\n')}
const out = {};
const body = (svg: string) => svg.replace(/^[\\s\\S]*?<svg[^>]*>/, '').replace(/<\\/svg>\\s*$/, '').trim();
const icon = (shapes: string, filled = false) => ({ shapes, filled });
${defs}
${tail}
${later}
export default out;
`;
const dir = mkdtempSync(join(tmpdir(), 'linkord-icons-'));
const file = join(dir, 'icons.ts');
writeFileSync(file, module);
const icons = (await import(pathToFileURL(file).href)).default;
rmSync(dir, { recursive: true });
// Android-only icons (the phone's own UI): Heroicons files by name.
const extra = { HomeSolid: '24/solid/home.svg', MicSolid: '24/solid/microphone.svg', PlaySolid: '24/solid/play.svg', PauseSolid: '24/solid/pause.svg', SmileSolid: '24/solid/face-smile.svg' };
for (const [name, file] of Object.entries(extra)) {
  const svg = readFileSync(join(root, 'app/node_modules/heroicons', file), 'utf8');
  icons[name] = { shapes: svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim(), filled: true };
}
// Android-only outline icons (the emoji picker's Recent tab; moderation: ban, kick, the section's shield).
const extraOutline = { Clock: '24/outline/clock.svg', NoSymbol: '24/outline/no-symbol.svg', UserMinus: '24/outline/user-minus.svg', Shield: '24/outline/shield-check.svg' };
for (const [name, file] of Object.entries(extraOutline)) {
  const svg = readFileSync(join(root, 'app/node_modules/heroicons', file), 'utf8');
  icons[name] = { shapes: svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim(), filled: false };
}

// 3. SVG elements -> paths.
const attr = (el, name) => el.match(new RegExp(`\\s${name}="([^"]*)"`))?.[1];
function paths(shapes, filled) {
  const list = [];
  for (const [el, tag] of shapes.matchAll(/<(path|circle)\b[^>]*\/?>/g)) {
    let d = attr(el, 'd');
    if (tag === 'circle') {
      const [cx, cy, r] = ['cx', 'cy', 'r'].map((a) => Number(attr(el, a)));
      d = `M${cx - r},${cy}a${r},${r} 0 1,0 ${2 * r},0a${r},${r} 0 1,0 ${-2 * r},0Z`;
    }
    const fill = filled || attr(el, 'fill') === 'currentColor';
    const stroke = !filled && attr(el, 'stroke') !== 'none';
    list.push({ d, fill, stroke: stroke && !(fill && attr(el, 'stroke') === 'none'), width: Number(attr(el, 'stroke-width') ?? 1.5), evenOdd: attr(el, 'fill-rule') === 'evenodd' });
  }
  return list;
}

const kt = (s) => JSON.stringify(s).replace(/\$/g, '\\$');
const names = Object.keys(icons).sort();
let code = `// Generated by android/scripts/gen-icons.mjs from app/src/components/Icons.tsx. Don't edit: change Icons.tsx and
// run the script again. Heroicons (MIT, https://heroicons.com) plus the shapes Linkord draws on the same grid.
package com.linkord.designsystem

import androidx.compose.ui.graphics.vector.ImageVector

@Suppress("unused")
object LinkordIcons {
`;
for (const n of names) {
  const ic = icons[n];
  const ps = paths(ic.shapes, ic.filled);
  if (!ps.length) throw new Error(`no shapes for ${n}`);
  const args = ps.map((p) => `P(${kt(p.d)}${p.stroke ? '' : ', stroke = false'}${p.fill ? ', fill = true' : ''}${p.width !== 1.5 ? `, width = ${p.width}f` : ''}${p.evenOdd ? ', evenOdd = true' : ''})`);
  code += `    val ${n}: ImageVector by lazy { icon(${kt(n)}, ${ic.rotate ?? 0}f, ${args.join(', ')}) }\n`;
}
code += '}\n';
writeFileSync(out, code);
console.log(`${names.length} icons -> ${out.slice(root.length)}`);

// 4. Profile link brand marks (app/src/lib/brand-icons.ts, Simple Icons) -> BrandIcons.kt, with the same host matching.
const { BRANDS } = await import(pathToFileURL(join(root, 'app/src/lib/brand-icons.ts')).href);
const brandOut = join(root, 'android/designsystem/src/main/kotlin/com/linkord/designsystem/BrandIcons.kt');
let brands = `// Generated by android/scripts/gen-icons.mjs from app/src/lib/brand-icons.ts. Don't edit: add a site to
// app/scripts/brand-icons.py, rerun it, then this script. Shapes from Simple Icons (CC0, simpleicons.org).
package com.linkord.designsystem

/** A site a profile link can go to, drawn with its own mark (filled, one path on a 24px grid). */
class Brand(val id: String, val name: String, val hosts: List<String>, val path: String)

object BrandIcons {
    val all = listOf(
`;
for (const b of BRANDS) brands += `        Brand(${kt(b.id)}, ${kt(b.name)}, listOf(${b.hosts.map(kt).join(', ')}), ${kt(b.path)}),\n`;
brands += `    )
}
`;
writeFileSync(brandOut, brands);
console.log(`${BRANDS.length} brands -> ${brandOut.slice(root.length)}`);
